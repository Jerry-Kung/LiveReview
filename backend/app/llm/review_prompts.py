# —— 第四轮：金句采集 ——
_QUOTES_TASK = """## 本次任务：优秀话术采集

只做一件事：从这一场的转写里挑出**值得反复使用**的原话，供人工摘取后复用。

入选的理由可以是下列任一种：

1. **有效**：该话术出现时段的表达明显比其他部分更完整、更有说服力（如把参数翻译成了
   生活场景）。
2. **品牌标杆**：话术契合「安静但专业、场景化、有高级感」的品牌调性，可作为其他主播的
   学习范本。
3. **创新**：用了一个此前没见过的切入方式（场景、对比、类比）且表达完整。
4. **问题修复**：主播在本场用一句话把某个容易讲错的地方讲对了（如报价前的价值铺垫）。

要求：

- 只挑**主播自己的原话**，逐字引用，不要改写、不要润色、不要合并两句成一句。
- 每条给出时间、所属分类（开场钩子 / 产品塑品 / 互动留人 / 转化引导 / 品牌叙事 /
  答疑应对 / 节奏调控）、适用场景，以及它好在哪。
- 宁缺毋滥：本场没有值得收录的话术时返回空数组。不要为了凑数把普通表述收进来——话术库
  被普通表述填满之后就没人会去查它了。
"""

_QUOTES_CONTRACT = """## 输出契约

只输出一个 JSON 对象，不要输出对象以外的任何文字（不要 Markdown 围栏、不要解释）。

{
  "quotes": [
    {
      "start_seconds": 0.0,
      "end_seconds": 0.0,
      "text": "主播原话，逐字引用",
      "category": "开场钩子 | 产品塑品 | 互动留人 | 转化引导 | 品牌叙事 | 答疑应对 | 节奏调控",
      "scene": "适用场景",
      "effect": "这句好在哪"
    }
  ]
}

约束：

- 时间为**原视频的绝对秒数**，保留一位小数。
- 没有值得收录的话术时输出 `{"quotes": []}`。
- `text` 不得改写、不得翻译、不得概括。
"""


# 每一轮的题面与契约。公共段由 `SHARED_GUIDELINE` 统一提供，各轮不重复。
_PASS_BODIES: dict[str, tuple[str, str]] = {
    PASS_STRUCTURE: (_STRUCTURE_TASK, _STRUCTURE_CONTRACT),
    PASS_CHECKS: (_CHECKS_TASK, _CHECKS_CONTRACT),
    PASS_ATTRIBUTION: (_ATTRIBUTION_TASK, _ATTRIBUTION_CONTRACT),
    PASS_QUOTES: (_QUOTES_TASK, _QUOTES_CONTRACT),
}


def pass_task(pass_name: str) -> str:
    """取某一轮的题面（含按需注入的心法清单与样板库）。"""
    task, _ = _PASS_BODIES[pass_name]
    if pass_name == PASS_CHECKS:
        # 检核轮与归因轮要用编号，因此把心法清单与样板库渲染进题面。渲染的取值直接取自
        # `mindset.py`，与界面查编号用的是同一份数据，避免「提示词换了、界面没换」
        return task.format(index=render_mindset_index(), samples=render_script_samples())
    if pass_name == PASS_ATTRIBUTION:
        # 归因轮的输入里已经带上了心法清单与样板库（由调用方拼进用户消息），题面里只留要求
        return task
    return task


def pass_contract(pass_name: str) -> str:
    """取某一轮的输出契约。"""
    return _PASS_BODIES[pass_name][1]


def build_pass_system_prompt(pass_name: str) -> str:
    """System 消息：公共准则 + 本轮题面 + 本轮输出契约。

    公共段每轮都发一遍，而不是拆进用户消息：它是**评判口径**（什么算好直播、什么不可推断），
    与「这一轮要回答什么」是同一层级的事，放在 system 里才不会被当成素材的一部分。
    """
    if pass_name not in _PASS_BODIES:
        raise KeyError(f"未知的复盘轮次：{pass_name}")
    parts = [f"你是【直播间智能复盘 Agent】，负责对一场商业营销直播做单场复盘。", SHARED_GUIDELINE]
    if pass_name == PASS_CHECKS:
        parts.append(_VIOLATION_LIBRARY.format(terms=render_violation_terms()))
    parts.append(pass_task(pass_name))
    parts.append(pass_contract(pass_name))
    return "\n".join(parts)


_VIOLATION_LIBRARY = """## 违规表达词库（检核用）

以下表达在直播话术中严禁出现，命中即计入 `violations` 并给出合规替换：

{terms}
"""


def build_pass_user_prompt(
    pass_name: str,
    *,
    filename: str | None,
    duration_seconds: float | None,
    clip_count: int,
    succeeded_clip_count: int,
    failed_clip_count: int,
    segment_count: int,
    transcript: str = "",
    part: tuple[int, int] | None = None,
    total_parts: int = 1,
    prior: str = "",
) -> str:
    """User 消息：本场基本信息 + （转写全文 或 前序轮次的结构化产出）。

    两种输入形态对应两类轮次：结构 / 检核 / 金句轮吃转写（可能分批），归因轮吃前序产出。
    `part` 非空表示这是分批输入中的第 `part[0]` 批，必须说明「本次只是全场的一部分」，
    否则模型会把半场的观察当成整场结论。
    """
    lines = [
        "## 本场素材",
        f"- 文件名：{filename or '未命名录屏'}",
        f"- 总时长：{duration_seconds:.1f} 秒" if duration_seconds is not None else "- 总时长：未知",
        f"- 片段：共 {clip_count} 片，识别成功 {succeeded_clip_count} 片，失败 {failed_clip_count} 片",
        f"- 语音记录：{segment_count} 条",
    ]
    if failed_clip_count:
        lines.append(
            f"- 注意：有 {failed_clip_count} 片识别失败，这些时段的语音内容完全缺失，"
            "不要据此外推、补全或据此判断「这一段没有内容」；"
            "涉及这些时段的结论须标注为推断，并写进 missing_info"
        )

    if part is not None and total_parts > 1:
        index, total = part
        lines.append(
            f"- 注意：这是转写的**分批输入**，本批为第 {index}/{total} 批，"
            "只覆盖全场的一部分；不要用本批内容概括整场，也不要假设未提供的时段没有内容"
        )

    if prior:
        lines.append("")
        lines.append("## 前序轮次的结构化结论（本次归因的唯一依据）")
        lines.append(prior)
    else:
        lines.append("")
        lines.append("## 语音转写全文（格式：[时间] 内容（语气））")
        lines.append(transcript)

    lines.append("")
    lines.append("请按本轮任务的输出契约给出结论。")
    return "\n".join(lines)


